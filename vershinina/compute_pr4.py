"""Расчёты для ПР4 Вершининой — нечёткая классификационная модель.

Вариант 11. Область принятия решений — расчёт потребления бензина
автомобилем. Лингвистические переменные: тип совершаемых маневров,
уровень подготовки водителя, рабочий объём двигателя (тип автомобиля),
техническое состояние автомобиля.

Эталонные классы — категории расхода бензина:
C1 — низкий расход (5-7 л/100 км);
C2 — средний расход (7-10 л/100 км);
C3 — высокий расход (10-14 л/100 км).

Алгоритм классификации (нечёткая конъюнкция):
  μ_C(o) = min_i μ_{T_C^i}(o_i),
где T_C^i — терм i-й переменной, входящий в эталонный класс C.
Объект относится к классу C* = argmax_C μ_C(o).
"""

# Универсумы входных лингвистических переменных
X1 = [0, 25, 50, 75, 100]   # тип маневров: доля резких ускорений/торможений, %
X2 = [0, 5, 10, 20, 30]     # уровень подготовки водителя: стаж, лет
X3 = [1.0, 1.5, 2.0, 3.0, 4.0]  # рабочий объём двигателя, л
X4 = [0, 25, 50, 75, 100]   # износ автомобиля, %

UNIVERSES = {
    "X1": X1,
    "X2": X2,
    "X3": X3,
    "X4": X4,
}

# Лингвистическая переменная X1 «тип маневров»
T1 = {
    "спокойный":   {0: 1.0, 25: 0.6, 50: 0.1, 75: 0.0, 100: 0.0},
    "умеренный":   {0: 0.2, 25: 0.8, 50: 1.0, 75: 0.4, 100: 0.0},
    "агрессивный": {0: 0.0, 25: 0.0, 50: 0.2, 75: 0.7, 100: 1.0},
}

# Лингвистическая переменная X2 «уровень подготовки водителя» (стаж, лет)
T2 = {
    "начинающий": {0: 1.0, 5: 0.7, 10: 0.2, 20: 0.0, 30: 0.0},
    "средний":    {0: 0.1, 5: 0.6, 10: 1.0, 20: 0.5, 30: 0.1},
    "опытный":    {0: 0.0, 5: 0.0, 10: 0.3, 20: 0.8, 30: 1.0},
}

# Лингвистическая переменная X3 «тип автомобиля» (рабочий объём двигателя, л)
T3 = {
    "малолитражка": {1.0: 1.0, 1.5: 0.7, 2.0: 0.2, 3.0: 0.0, 4.0: 0.0},
    "средний":      {1.0: 0.1, 1.5: 0.5, 2.0: 1.0, 3.0: 0.4, 4.0: 0.0},
    "крупный":      {1.0: 0.0, 1.5: 0.0, 2.0: 0.2, 3.0: 0.8, 4.0: 1.0},
}

# Лингвистическая переменная X4 «техническое состояние автомобиля» (износ, %)
T4 = {
    "отличное":          {0: 1.0, 25: 0.7, 50: 0.2, 75: 0.0, 100: 0.0},
    "удовлетворительное":{0: 0.1, 25: 0.6, 50: 1.0, 75: 0.5, 100: 0.1},
    "плохое":            {0: 0.0, 25: 0.0, 50: 0.3, 75: 0.8, 100: 1.0},
}

TERMS = {
    "X1": T1,
    "X2": T2,
    "X3": T3,
    "X4": T4,
}

# Эталонные классы: расход бензина
# Каждый класс — комбинация термов входных переменных
CLASSES = {
    "C1_низкий": {
        "label": "C₁ низкий расход (5-7 л/100 км)",
        "X1": "спокойный",
        "X2": "опытный",
        "X3": "малолитражка",
        "X4": "отличное",
    },
    "C2_средний": {
        "label": "C₂ средний расход (7-10 л/100 км)",
        "X1": "умеренный",
        "X2": "средний",
        "X3": "средний",
        "X4": "удовлетворительное",
    },
    "C3_высокий": {
        "label": "C₃ высокий расход (10-14 л/100 км)",
        "X1": "агрессивный",
        "X2": "начинающий",
        "X3": "крупный",
        "X4": "плохое",
    },
}


def membership(var_name, term_name, value):
    """Степень принадлежности μ_T(value) — кусочно-линейная интерполяция
    по узлам универсума. Если value совпадает с узлом — берём табличное
    значение, иначе линейно интерполируем между двумя соседними узлами."""
    universe = UNIVERSES[var_name]
    term = TERMS[var_name][term_name]
    if value <= universe[0]:
        return term[universe[0]]
    if value >= universe[-1]:
        return term[universe[-1]]
    for i in range(len(universe) - 1):
        x0, x1 = universe[i], universe[i + 1]
        if x0 <= value <= x1:
            mu0, mu1 = term[x0], term[x1]
            if x1 == x0:
                return mu0
            return mu0 + (mu1 - mu0) * (value - x0) / (x1 - x0)
    return 0.0


def classify(observation):
    """Классификация наблюдения. observation — dict {X1, X2, X3, X4}.
    Возвращает {class_key: μ_C}."""
    result = {}
    for c_key, c_def in CLASSES.items():
        mus = []
        for var in ("X1", "X2", "X3", "X4"):
            term = c_def[var]
            mu = membership(var, term, observation[var])
            mus.append(mu)
        result[c_key] = min(mus)
    return result


def classify_detailed(observation):
    """То же, но возвращает полную таблицу μ по каждой переменной."""
    rows = []
    for c_key, c_def in CLASSES.items():
        per_var = {}
        for var in ("X1", "X2", "X3", "X4"):
            term = c_def[var]
            mu = membership(var, term, observation[var])
            per_var[var] = (term, mu)
        per_var["min"] = min(mu for (_, mu) in per_var.values())
        rows.append((c_key, c_def["label"], per_var))
    return rows


if __name__ == "__main__":
    print("=== Эталонные классы ===")
    for k, v in CLASSES.items():
        print(f"  {v['label']}")
        for var in ("X1", "X2", "X3", "X4"):
            print(f"    {var}: {v[var]}")
        print()

    # Числовой пример: реальный водитель
    observation = {
        "X1": 35,    # 35% доли резких маневров — умеренно-активный стиль
        "X2": 8,     # 8 лет стажа — средний водитель
        "X3": 1.6,   # 1.6 л — между малолитражкой и средним
        "X4": 30,    # 30% износа — между отличным и удовлетворительным
    }
    print("=== Наблюдение ===")
    for k, v in observation.items():
        print(f"  {k} = {v}")

    print("\n=== Расчёт принадлежности к классам ===")
    rows = classify_detailed(observation)
    for c_key, label, per_var in rows:
        print(f"\n{label}")
        for var in ("X1", "X2", "X3", "X4"):
            term, mu = per_var[var]
            print(f"  μ_{{{var} есть {term}}}({observation[var]}) = {mu:.3f}")
        print(f"  μ_C = min(...) = {per_var['min']:.3f}")

    result = classify(observation)
    winner = max(result, key=result.get)
    print(f"\n=== Результат ===")
    print(f"  Класс-победитель: {CLASSES[winner]['label']}")
    print(f"  μ = {result[winner]:.3f}")
