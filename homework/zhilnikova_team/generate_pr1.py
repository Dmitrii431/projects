ROLES = ["КР", "НА", "НВ", "ИФ", "ЭК", "ДИ", "ПР", "ЗВ"]
ROLE_NAMES = {"КР": "Координатор", "НА": "Направляющий", "НВ": "Новатор",
              "ИФ": "Информатор", "ЭК": "Эксперт", "ДИ": "Дипломат",
              "ПР": "Практик", "ЗВ": "Завершающий"}
# ключ к тесту: буква варианта в колонке роли, по вопросам 1-7
KEY = ["гевазбжд", "бджвгеаз", "авгеждзб", "збджваге", "егздавбж",
       "вжаздбег", "жаегбздв"]
ANSWERS = ["гзж", "гз", "жбае", "зве", "абев", "вдг", "бва"]


def score():
    table, totals = [], {r: 0 for r in ROLES}
    for qi, chosen in enumerate(ANSWERS):
        row = []
        for ri, role in enumerate(ROLES):
            letter = KEY[qi][ri]
            hit = letter in chosen
            totals[role] += hit
            row.append(letter + (" ✓" if hit else ""))
        table.append(row)
    return table, totals


def chart(totals):
    order = sorted(ROLES, key=lambda r: -totals[r])
    vals = [totals[r] for r in order]
    colors = ["#003F7F" if v == max(vals) else
              "#4F81BD" if v >= 4 else "#B8C7DC" for v in vals]
    fig, ax = plt.subplots(figsize=(8, 3.8))
    bars = ax.bar([ROLE_NAMES[r] for r in order], vals, color=colors)
    for b, v in zip(bars, vals):
        ax.text(b.get_x() + b.get_width() / 2, v + 0.1, str(v), ha="center",
                fontsize=11)
    ax.set_ylabel("Баллы")
    ax.set_ylim(0, 7.8)
    ax.spines[["top", "right"]].set_visible(False)
    plt.xticks(rotation=20, fontsize=10)
    fig.tight_layout()
    fig.savefig(CHART, dpi=200)
    plt.close(fig)


