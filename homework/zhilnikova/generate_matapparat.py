def draw_scheme():
    fig, ax = plt.subplots(figsize=(11, 5.6))
    ax.set_xlim(0, 11)
    ax.set_ylim(0, 5.6)
    ax.axis("off")

    def box(x, y, w, hh, text, fc, fs=13, bold=False):
        ax.add_patch(FancyBboxPatch((x, y), w, hh, boxstyle="round,pad=0.03",
                                    fc=fc, ec="black", lw=1))
        ax.text(x + w / 2, y + hh / 2, text, ha="center", va="center",
                fontsize=fs, weight="bold" if bold else "normal",
                linespacing=1.3)

    def arrow(x1, y1, x2, y2):
        ax.annotate("", xy=(x2, y2), xytext=(x1, y1),
                    arrowprops=dict(arrowstyle="-|>", lw=1.3, color="black"))

    box(0.1, 0.9, 2.6, 3.4, "Входные параметры\n\nx₁ качество данных\n"
        "x₂ новизна решения\nx₃ компетентность\nкоманды\nx₄ регуляторная\n"
        "чувствительность\nx₅ угрозы ИБ\nx₆ орг. готовность", "#dfe8f5")
    box(3.8, 1.6, 3.4, 2.0, "Процесс управления\nрисками внедрения ИИ\n"
        "в IT-компании\n\nСППР: FMEA + нечёткий\nвывод Мамдани", "#f2f2f2",
        fs=13.5, bold=True)
    box(8.3, 0.9, 2.6, 3.4, "Выходные параметры\n\ny₁ интегральный\nриск R\n"
        "y₂ категория риска\ny₃ RPN рисков\ny₄ Accuracy, precision,\n"
        "recall\ny₅ доля неуспешных\nпроектов\ny₆ E(L), NPV", "#dff0dc", fs=12)
    box(3.4, 4.3, 4.2, 1.2, "Управляющие параметры\nu₁ глубина риск-анализа, "
        "u₂ бюджет мер,\nu₃ мониторинг модели, u₄ масштаб пилота,\n"
        "u₅ пороги категорий", "#fdf1d6", fs=12)
    box(3.4, 0.05, 4.2, 1.0, "Ограничения\ng₁ требования законодательства, "
        "g₂ R ≤ Rдоп,\ng₃ Z ≤ Zбюджет, g₄ W ≥ 0,7", "#f7dede", fs=12)
    arrow(2.7, 2.6, 3.8, 2.6)
    arrow(7.2, 2.6, 8.3, 2.6)
    arrow(5.5, 4.3, 5.5, 3.6)
    arrow(5.5, 1.05, 5.5, 1.6)
    fig.savefig(SCHEME, dpi=200, bbox_inches="tight")
    plt.close(fig)


