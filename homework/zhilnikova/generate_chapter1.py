def add_chapter_title(doc, text):
    add_centered(doc, text, bold=True, size=14, line_spacing=1.5,
                 space_before=0, space_after=12)


def add_section_heading(doc, text):
    return add_par(doc, text, bold=True, align=WD_ALIGN_PARAGRAPH.LEFT,
                   size=14, line_spacing=1.5, space_before=12, space_after=6)


def add_body(doc, text):
    return add_par(doc, text, align=WD_ALIGN_PARAGRAPH.JUSTIFY, size=14,
                   line_spacing=1.5, first_line_indent=Cm(1.25),
                   space_after=0)


def add_list_item(doc, text):
    return add_par(doc, text, align=WD_ALIGN_PARAGRAPH.JUSTIFY, size=14,
                   line_spacing=1.5, first_line_indent=Cm(1.25),
                   space_after=0)


def add_ref_item(doc, n, text):
    """Bibliography item: '1.   Author... — Publisher, year. — N с.'"""
    p = doc.add_paragraph()
    p.alignment = WD_ALIGN_PARAGRAPH.JUSTIFY
    pf = p.paragraph_format
    pf.line_spacing = 1.5
    pf.first_line_indent = Cm(1.25)
    pf.space_after = Pt(0)
    r = p.add_run(f"{n}. {text}")
    set_font(r, size=14)


