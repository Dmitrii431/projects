def main():
    os.makedirs(IMG_DIR, exist_ok=True)
    doc = Document()
    add_title_page(doc, pr_number=1, pr_title="Метод парных сравнений")

    # Цель работы.
    add_heading(doc, "Цель работы", level=2)
    add_body(
        doc,
        "Ознакомиться с методом парных сравнений, применить его для ранжирования "
        "альтернатив (целей) и определения их весов, сделать обоснованный выбор "
        "наиболее предпочтительного варианта.",
    )

    # Описание метода.
    add_heading(doc, "Краткое описание метода", level=2)
    add_body(
        doc,
        "Метод парных сравнений основан на попарном сравнении объектов (целей, альтернатив). "
        "Каждая пара сравнивается по правилу: если i-й объект предпочтительнее j-го, то "
        "a_ij = 2; если они равнозначны — a_ij = 1; если i-й уступает j-му — a_ij = 0. "
        "На диагонали матрицы всегда стоят единицы (объект сравнивается сам с собой).",
    )
    add_body(
        doc,
        "После заполнения матрицы по каждой строке подсчитывается сумма оценок S_i. "
        "Относительный вес i-й цели вычисляется как V_i = S_i / Σ S_i. Ранжирование целей "
        "производится по убыванию весов V_i.",
    )

    # Постановка задачи.
    add_heading(doc, "Постановка задачи", level=2)
    add_body(
        doc,
        "Строительная компания рассматривает предложения от четырёх компаний-поставщиков "
        "строительных материалов (Z1, Z2, Z3, Z4). Требуется методом парных сравнений "
        "проранжировать альтернативы и определить наиболее предпочтительный вариант для "
        "заключения договора поставки.",
    )
    add_body(
        doc,
        "Решение выполнено для трёх вариантов исходных данных. Расчёты произведены в "
        "Microsoft Excel с использованием формул СУММ и деления на общую сумму.",
    )

    fig_num = 1
    for v in VARIANTS:
        add_heading(doc, f"Вариант {v['num']}", level=2)

        # Исходная матрица — Word-таблица.
        add_paragraph(
            doc,
            f"Исходная матрица парных сравнений для варианта {v['num']}:",
            align=WD_ALIGN_PARAGRAPH.LEFT,
            size=14,
        )
        headers = ["Zi/Zj", "Z1", "Z2", "Z3", "Z4"]
        rows = []
        for i, row_vals in enumerate(v["data"], start=1):
            rows.append([f"Z{i}", *row_vals])
        add_data_table(doc, headers, rows)
        add_paragraph(doc, "", size=8)

        # Рисунок — скриншот из Excel с расчётами.
        add_body(
            doc,
            "В таблице ниже (рис. " + str(fig_num) + ") приведён полный расчёт: сумма "
            "оценок по строкам, итоговая сумма 16, а также нормированные веса целей. "
            "Расчёт суммы выполнен функцией СУММ, веса — делением суммы строки на итог.",
        )
        png = os.path.join(IMG_DIR, f"variant_{v['num']}.png")
        xlsx_sheet_to_png(XLSX, v["sheet"], png)
        add_figure(
            doc,
            png,
            f"Рисунок {fig_num} — Расчёт метода парных сравнений для варианта {v['num']}",
            max_width_cm=15.5,
        )
        fig_num += 1

        # Вывод по варианту.
        add_paragraph(
            doc,
            f"Порядок предпочтения целей: {v['result']}.",
            align=WD_ALIGN_PARAGRAPH.LEFT,
            size=14,
        )
        add_paragraph(
            doc,
            f"Веса: {v['weights_text']}.",
            align=WD_ALIGN_PARAGRAPH.LEFT,
            size=14,
        )
        add_body(
            doc,
            f"Вывод по варианту {v['num']}: наиболее предпочтительным является вариант "
            f"{v['winner']} с наибольшим весом {v['winner_weight']}. Этой компании-поставщику "
            f"и следует отдать предпочтение при заключении договора.",
        )

    # Общий вывод.
    add_heading(doc, "Общий вывод по работе", level=2)
    add_body(
        doc,
        "В ходе выполнения работы метод парных сравнений применён для трёх вариантов "
        "исходных данных. Для каждого варианта построена матрица парных сравнений, "
        "подсчитаны суммы оценок и нормированные веса целей, проведено ранжирование "
        "альтернатив и выбран наилучший вариант.",
    )
    add_body(
        doc,
        "Метод парных сравнений является простым и наглядным инструментом при "
        "многокритериальном выборе, особенно когда исходная информация представлена "
        "в виде экспертных оценок. Его достоинство — небольшое число сравнений и "
        "чёткое ранжирование. Ограничение — возможная несогласованность оценок при "
        "большом числе объектов, требующая дополнительной проверки.",
    )

    out = os.path.join(OUT_DIR, "Отчёт_ПР1_Метод_парных_сравнений_Рослов.docx")
    doc.save(out)
    print("OK:", out)


if __name__ == "__main__":
    main()
