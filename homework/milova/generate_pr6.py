def add_toc(doc):
    add_paragraph(
        doc,
        "СОДЕРЖАНИЕ",
        bold=True,
        align=WD_ALIGN_PARAGRAPH.CENTER,
        size=14,
        line_spacing=1.5,
        space_after=12,
    )
    items = [
        ("Введение", 3),
        ("1. Задача принятия группового решения", 4),
        ("2. Правило большинства голосов и принцип Кондорсе", 6),
        ("3. Метод Борда", 9),
        ("4. Парадокс Эрроу", 11),
        ("5. Пример использования: выбор системы менеджмента качества", 13),
        ("Заключение", 16),
        ("Список использованных источников", 17),
    ]
    for title, page in items:
        p = doc.add_paragraph()
        p.paragraph_format.line_spacing = 1.5
        p.paragraph_format.space_after = Pt(0)
        tab_stops = p.paragraph_format.tab_stops
        tab_stops.add_tab_stop(Cm(16), WD_ALIGN_PARAGRAPH.RIGHT, leader=2)  # 2 = dots
        r = p.add_run(title)
        set_font(r, size=14)
        r = p.add_run(f"\t{page}")
        set_font(r, size=14)
    doc.add_page_break()


