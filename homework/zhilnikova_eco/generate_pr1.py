def set_font(run, name="Times New Roman", size=14, bold=False, italic=False):
    run.font.name = name
    run.font.size = Pt(size)
    run.bold = bold
    run.italic = italic
    rpr = run._element.get_or_add_rPr()
    rFonts = rpr.find(qn("w:rFonts"))
    if rFonts is None:
        rFonts = OxmlElement("w:rFonts")
        rpr.append(rFonts)
    for a in ("w:ascii", "w:hAnsi", "w:cs"):
        rFonts.set(qn(a), name)


def configure(doc):
    for section in doc.sections:
        section.page_height = Mm(297)
        section.page_width = Mm(210)
        section.top_margin = Cm(2)
        section.bottom_margin = Cm(2)
        section.left_margin = Cm(3)
        section.right_margin = Cm(1.5)
    style = doc.styles["Normal"]
    style.font.name = "Times New Roman"
    style.font.size = Pt(14)
    rpr = style.element.get_or_add_rPr()
    rFonts = rpr.find(qn("w:rFonts"))
    if rFonts is None:
        rFonts = OxmlElement("w:rFonts")
        rpr.append(rFonts)
    for a in ("w:ascii", "w:hAnsi", "w:cs"):
        rFonts.set(qn(a), "Times New Roman")


def add_par(doc, text, *, bold=False, italic=False, align=None, size=14,
            first_line_indent=None, line_spacing=1.5, space_after=0,
            space_before=0):
    p = doc.add_paragraph()
    if align is not None:
        p.alignment = align
    pf = p.paragraph_format
    pf.space_after = Pt(space_after)
    pf.space_before = Pt(space_before)
    pf.line_spacing = line_spacing
    if first_line_indent is not None:
        pf.first_line_indent = first_line_indent
    for i, line in enumerate(text.split("\n")):
        if i > 0:
            p.add_run().add_break()
        set_font(p.add_run(line), size=size, bold=bold, italic=italic)
    return p


def add_centered(doc, text, **kw):
    kw.setdefault("align", WD_ALIGN_PARAGRAPH.CENTER)
    return add_par(doc, text, **kw)


def body(doc, text):
    return add_par(doc, text, align=WD_ALIGN_PARAGRAPH.JUSTIFY,
                   first_line_indent=Cm(1.25), space_after=2)


def heading(doc, text, *, space_before=12):
    return add_par(doc, text, bold=True, align=WD_ALIGN_PARAGRAPH.LEFT,
                   first_line_indent=Cm(1.25), space_before=space_before,
                   space_after=6)


def caption(doc, text):
    return add_par(doc, text, align=WD_ALIGN_PARAGRAPH.RIGHT, size=12,
                   line_spacing=1.0, space_before=10, space_after=2)


def table_title(doc, text):
    return add_par(doc, text, align=WD_ALIGN_PARAGRAPH.CENTER, size=12,
                   line_spacing=1.0, space_after=6)


def _set_cell_borders(cell, top=False, bottom=False):
    tc_pr = cell._tc.get_or_add_tcPr()
    tc_borders = tc_pr.find(qn("w:tcBorders"))
    if tc_borders is None:
        tc_borders = OxmlElement("w:tcBorders")
        tc_pr.append(tc_borders)
    for edge in ("top", "left", "bottom", "right"):
        el = tc_borders.find(qn(f"w:{edge}"))
        if el is None:
            el = OxmlElement(f"w:{edge}")
            tc_borders.append(el)
        if (edge == "top" and top) or (edge == "bottom" and bottom):
            el.set(qn("w:val"), "single")
            el.set(qn("w:sz"), "6")
            el.set(qn("w:color"), "000000")
        else:
            el.set(qn("w:val"), "nil")


def _cell_par(cell, text, *, align=WD_ALIGN_PARAGRAPH.CENTER, size=12,
              italic=False, bold=False, line_spacing=1.0, color=None):
    p = cell.paragraphs[0] if not cell.paragraphs[0].text else cell.add_paragraph()
    p.alignment = align
    pf = p.paragraph_format
    pf.line_spacing = line_spacing
    pf.space_after = Pt(0)
    pf.space_before = Pt(0)
    for i, line in enumerate(str(text).split("\n")):
        if i > 0:
            p.add_run().add_break()
        r = p.add_run(line)
        set_font(r, size=size, italic=italic, bold=bold)
        if color:
            r.font.color.rgb = color
    return p


def signature_block(doc, *, top_left, top_right, bottom_left, bottom_middle,
                    bottom_right, widths=(6.0, 5.5, 5.0)):
    table = doc.add_table(rows=2, cols=3)
    table.autofit = False
    for i, w in enumerate(widths):
        for row in table.rows:
            row.cells[i].width = Cm(w)
    for i, val in enumerate([top_left, "", top_right]):
        c = table.rows[0].cells[i]
        _set_cell_borders(c)
        _cell_par(c, val, size=12)
    for i, val in enumerate([bottom_left, bottom_middle, bottom_right]):
        c = table.rows[1].cells[i]
        _set_cell_borders(c, top=True)
        _cell_par(c, val, size=10, italic=True)
    return table


def _fixed_layout(t, widths):
    tblPr = t._tbl.tblPr
    for tag in ("w:tblLayout", "w:tblW"):
        el = tblPr.find(qn(tag))
        if el is not None:
            tblPr.remove(el)
    lay = OxmlElement("w:tblLayout")
    lay.set(qn("w:type"), "fixed")
    tblPr.append(lay)
    tw = OxmlElement("w:tblW")
    tw.set(qn("w:w"), str(int(sum(widths) * 567)))
    tw.set(qn("w:type"), "dxa")
    tblPr.append(tw)
    grid_el = t._tbl.find(qn("w:tblGrid"))
    if grid_el is not None:
        t._tbl.remove(grid_el)
    grid_el = OxmlElement("w:tblGrid")
    for w in widths:
        gc = OxmlElement("w:gridCol")
        gc.set(qn("w:w"), str(int(w * 567)))
        grid_el.append(gc)
    t._tbl.insert(1, grid_el)


def grid(doc, rows, widths, *, size=11, header_bold=True, aligns=None):
    """Таблица с сеткой. rows[0] — шапка."""
    t = doc.add_table(rows=len(rows), cols=len(widths))
    t.style = "Table Grid"
    t.autofit = False
    _fixed_layout(t, widths)
    for ri, row in enumerate(rows):
        for ci, val in enumerate(row):
            cell = t.rows[ri].cells[ci]
            cell.width = Cm(widths[ci])
            if ci == 0 and ri == 0:
                for r in t.rows:
                    r.cells[ci].width = Cm(widths[ci])
            al = WD_ALIGN_PARAGRAPH.CENTER
            if ri > 0 and aligns:
                al = aligns[ci]
            _cell_par(cell, val, align=al, size=size,
                      bold=(ri == 0 and header_bold))
    for ci, w in enumerate(widths):
        for r in t.rows:
            r.cells[ci].width = Cm(w)
    return t


